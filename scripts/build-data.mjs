// Converts raw downloads into the bundled dataset used by the website.
//   node scripts/build-data.mjs <raw.json> <yields.json>
// raw.json   : NASA POWER monthly weather + ISRIC SoilGrids v2 soil (fetched by scripts/fetch-data.mjs)
// yields.json: State-wise yield tables, RBI Handbook of Statistics on Indian States (source: MoA&FW)
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const [rawPath, yieldPath] = process.argv.slice(2);
const raw = JSON.parse(readFileSync(rawPath, 'utf8'));
const yields = JSON.parse(readFileSync(yieldPath, 'utf8'));

const round = (v, d = 1) => (v == null || Number.isNaN(v) ? null : Math.round(v * 10 ** d) / 10 ** d);

// ---- Weather: one row per month ----
const weather = [];
for (const r of raw.regions) {
  const p = r.weather;
  for (const key of Object.keys(p.T2M)) {
    const month = Number(key.slice(4));
    if (month === 13) continue; // annual summary row from the API
    const v = (k) => (p[k][key] === -999 ? null : p[k][key]);
    weather.push({
      region: r.id,
      date: `${key.slice(0, 4)}-${key.slice(4)}`,
      tMean: round(v('T2M')),
      tMax: round(v('T2M_MAX')),
      tMin: round(v('T2M_MIN')),
      humidity: round(v('RH2M')),
      rainfall: round(v('PRECTOTCORR_SUM')),
    });
  }
}

// ---- Soil: depth-weighted 0-30 cm mean of each sample point, then mean of points ----
const depthW = { '0-5cm': 5, '5-15cm': 10, '15-30cm': 15 };
const soil = raw.regions.map((r) => {
  const props = {};
  const points = [];
  for (const s of r.soils) {
    if (!s.data) continue;
    const pt = {};
    for (const layer of s.data) {
      let sum = 0, w = 0;
      for (const d of layer.depths) {
        const m = d.values.mean;
        if (m == null) continue;
        sum += (m / layer.unit_measure.d_factor) * depthW[d.label];
        w += depthW[d.label];
      }
      if (w > 0) pt[layer.name] = sum / w;
    }
    if (Object.keys(pt).length) points.push({ lat: s.lat, lon: s.lon, ...pt });
  }
  for (const k of ['phh2o', 'soc', 'nitrogen', 'clay', 'sand', 'silt', 'cec', 'bdod']) {
    const vals = points.map((p) => p[k]).filter((x) => x != null);
    props[k] = vals.length ? vals.reduce((a, b) => a + b, 0) / vals.length : null;
  }
  return {
    region: r.id,
    samplePoints: points.length,
    ph: round(props.phh2o, 2),
    organicCarbon: round(props.soc, 1), // g/kg
    nitrogen: round(props.nitrogen, 2), // g/kg (total N)
    clay: round(props.clay, 1), // %
    sand: round(props.sand, 1), // %
    silt: round(props.silt, 1), // %
    cec: round(props.cec, 1), // cmol(c)/kg
    bulkDensity: round(props.bdod, 2), // kg/dm3
    points: points.map((p) => ({ lat: p.lat, lon: p.lon })),
  };
});

// ---- Yields ----
const nameToId = Object.fromEntries(raw.regions.map((r) => [r.name, r.id]));
nameToId['ALL INDIA'] = 'india';
const keep = ['rice', 'wheat', 'coarseCereals', 'pulses', 'oilseeds', 'sugarcane'];
const yieldRows = [];
for (const crop of keep) {
  const t = yields[crop];
  const years = t.years.map((y) => y.replace('*', ''));
  for (const [state, vals] of Object.entries(t.data)) {
    vals.forEach((v, i) => {
      if (v == null) return;
      yieldRows.push({
        region: nameToId[state],
        year: years[i],
        crop,
        yield: v,
        estimate: t.years[i].includes('*'),
      });
    });
  }
}

const regions = raw.regions.map((r) => ({
  id: r.id,
  name: r.name,
  station: r.station,
  lat: r.pts[0][0],
  lon: r.pts[0][1],
  elevation: round(r.elevation, 0),
}));

mkdirSync('src/data', { recursive: true });
const banner = '// Generated by scripts/build-data.mjs — do not edit by hand.\n';
writeFileSync('src/data/regions.json', JSON.stringify(regions, null, 1));
writeFileSync('src/data/weather.json', JSON.stringify(weather));
writeFileSync('src/data/soil.json', JSON.stringify(soil, null, 1));
writeFileSync('src/data/yields.json', JSON.stringify(yieldRows));
writeFileSync('src/data/meta.json', JSON.stringify({ fetchedAt: raw.fetchedAt }, null, 1));
console.log(banner, 'weather rows', weather.length, 'soil', soil.map((s) => `${s.region}:${s.samplePoints}`).join(' '), 'yield rows', yieldRows.length);
